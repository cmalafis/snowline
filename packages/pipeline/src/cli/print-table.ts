import { writeFile } from "node:fs/promises";
import { compassPoint, type Difficulty, type Run, type Zone } from "@snowline/core";
import { dataPath, loadResort, readJson } from "../resort.ts";

export const DIFFICULTY_SYMBOL: Record<Difficulty, string> = {
  novice: "●",
  easy: "●",
  intermediate: "■",
  advanced: "◆",
  expert: "◆◆",
  freeride: "◆◆",
  extreme: "◆◆",
  unknown: "?",
};

const COLUMNS = ["Run", "Diff", "Zone", "Type", "Top ft", "Bottom ft", "Pitch°", "Aspect", "Mixed", "Segs"] as const;

export function runRows(runs: Run[], zones: Zone[]): string[][] {
  const zoneName = new Map(zones.map((z) => [z.id, z.name]));
  return runs
    .filter((r) => r.name)
    .sort((a, b) => (zoneName.get(a.zone ?? "") ?? "").localeCompare(zoneName.get(b.zone ?? "") ?? "") || a.name!.localeCompare(b.name!))
    .map((r) => [
      r.name!,
      DIFFICULTY_SYMBOL[r.difficulty],
      zoneName.get(r.zone ?? "") ?? "—",
      r.type,
      r.topFt.toLocaleString("en-US"),
      r.bottomFt.toLocaleString("en-US"),
      r.pitchDeg.toFixed(1),
      `${String(r.aspectDeg).padStart(3)}° ${compassPoint(r.aspectDeg).padEnd(2)}`,
      r.mixedAspect ? `yes (${r.aspectSpreadDeg}°)` : "",
      String(r.segments.length),
    ]);
}

export function textTable(header: readonly string[], rows: string[][]): string {
  const widths = header.map((h, i) => Math.max(h.length, ...rows.map((r) => [...(r[i] ?? "")].length)));
  const line = (cells: readonly string[]) => cells.map((c, i) => c + " ".repeat(widths[i]! - [...c].length)).join("  ");
  return [line(header), widths.map((w) => "─".repeat(w)).join("  "), ...rows.map(line)].join("\n");
}

export function markdownTable(header: readonly string[], rows: string[][]): string {
  const esc = (s: string) => s.replace(/\|/g, "\\|");
  return [`| ${header.join(" | ")} |`, `|${header.map(() => "---").join("|")}|`, ...rows.map((r) => `| ${r.map(esc).join(" | ")} |`)].join("\n");
}

export async function printTable(resortId: string) {
  const cfg = await loadResort(resortId);
  const runs = await readJson<Run[]>(dataPath(cfg.id, "runs.json"));
  const zones = await readJson<Zone[]>(dataPath(cfg.id, "zones.json"));
  const rows = runRows(runs, zones);

  const zoneHeader = ["Zone", "Lifts", "Runs", "Mean aspect", "Top ft", "Bottom ft", "Wind-exposed"];
  const zoneRows = zones.map((z) => [
    z.name,
    z.lifts.join(", "),
    String(z.runCount),
    `${Math.round(z.aspectDeg)}° ${compassPoint(z.aspectDeg)}`,
    z.topFt.toLocaleString("en-US"),
    z.bottomFt.toLocaleString("en-US"),
    z.windExposed ? "yes" : "",
  ]);
  const source = runs[0]?.demSource === "3dep" ? "USGS 3DEP 10 m" : "Open-Meteo ~90 m (fallback)";
  const summary = `${rows.length} named runs, ${runs.filter((r) => r.mixedAspect).length} mixed-aspect, DEM: ${source}`;

  console.log(`\n${cfg.name} — zones\n`);
  console.log(textTable(zoneHeader, zoneRows));
  console.log(`\n${cfg.name} — runs (${summary})\n`);
  console.log(textTable(COLUMNS, rows));

  const md = [
    `# ${cfg.name} — run terrain`,
    "",
    `Generated by \`npm run pipeline -- ${cfg.id}\`. ${summary}. Aspect is the downhill direction of the DEM gradient (degrees from true north), length-weighted over ~50 m segments; "Mixed" means segment aspects span more than 90°.`,
    "",
    "## Zones",
    "",
    markdownTable(zoneHeader, zoneRows),
    "",
    "## Runs",
    "",
    markdownTable(COLUMNS, rows),
    "",
  ].join("\n");
  await writeFile(dataPath(cfg.id, "runs.md"), md);
}

if (import.meta.url === `file://${process.argv[1]}`) await printTable(process.argv[2]!);
